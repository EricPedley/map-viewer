function formatRouteStats(r) {
  return `${metersToMiles(r.totalDistanceMeters).toFixed(1)} mi · +${r.elevationGainMeters}m`;
}

function renderRouteList() {
  routeList.innerHTML = '';
  for (const r of routesIndex.routes) {
    const li = document.createElement('li');
    li.className = r.id === routeId ? 'selected' : '';
    li.innerHTML =
      `<span class="route-check">${r.id === routeId ? '✓' : ''}</span>` +
      `<span class="route-info"><span class="route-name">${escapeHtml(r.name)}</span>` +
      `<span class="route-meta">${formatRouteStats(r)}${r.poiCount ? ` · ${r.poiCount} POIs` : ''}</span></span>`;
    li.addEventListener('click', () => {
      closeAllPanels();
      if (r.id !== routeId) selectRoute(r.id);
    });
    routeList.appendChild(li);
  }
}

let mapHasView = false;
let selectToken = 0; // guards against a slow earlier load finishing after a later pick

async function selectRoute(id, { fit = true } = {}) {
  const load = routeModules[`./data/routes/${id}.json`];
  if (!load) throw new Error(`Unknown route: ${id}`);
  const token = ++selectToken;
  const meta = routesIndex.routes.find((r) => r.id === id);
  routeStatusEl.textContent = `Loading ${meta?.name ?? id}…`;
  positionPanels();
  routeStatusEl.hidden = false;

  let data;
  try {
    data = (await load()).default;
  } catch (err) {
    if (token === selectToken) routeStatusEl.textContent = `Couldn't load that route: ${err.message}`;
    return;
  }
  if (token !== selectToken) return;
  routeStatusEl.hidden = true;

  route = data;
  routeId = id;
  try {
    localStorage.setItem(SELECTED_ROUTE_KEY, id);
  } catch {
    /* storage unavailable — selection just won't persist */
  }

  // Give the map a view before adding layers (Leaflet throws if a marker is
  // added to a map that has no center/zoom yet, which is the case on first load).
  if (!mapHasView || (fit && !followMode.isActive())) {
    map.fitBounds(L.latLngBounds(route.track.map(([lat, lon]) => [lat, lon])), { padding: [24, 24] });
    mapHasView = true;
  }

  drawRoute();
  poiRouteDistance = route.pois.map((poi) =>
    nearestRouteDistanceMeters(route.track, route.distances, poi.lat, poi.lon)
  );
  // OSM-derived cues carry their exact distance along the route (`dist`),
  // which matters on loops that retrace a road; GPX cues are located by
  // nearest-point lookup.
  cueRouteDistance = route.cues.map(
    (cue) => cue.dist ?? nearestRouteDistanceMeters(route.track, route.distances, cue.lat, cue.lon)
  );

  // Hide markers for categories the user has filtered out, then refresh
  // everything else that shows route-specific data.
  renderPoiFilters();
  applyFilters();
  renderElevation();
  hoverMarker.setStyle({ opacity: 0, fillOpacity: 0 });
  btnRoutes.textContent = `🗺️ ${route.name}`;
  btnRoutes.title = route.name;
  positionPanels(); // chip text changed width, which can change the bar's row count
  renderRouteList();
  refreshOfflineEstimate();
  refreshCacheStatus();
  document.title = `${route.name} — Eric's Cycling App`;

  // If location is already on, re-place the rider on the new route (no hint:
  // it's a different track, so the old mileage means nothing).
  const here = locationTracker.getLatLng();
  currentMileageMeters = here
    ? nearestRouteDistanceMeters(route.track, route.distances, here.lat, here.lng)
    : null;
  renderPoiListItems();
  updateNavBanner();
}

const savedRouteId = (() => {
  try {
    return localStorage.getItem(SELECTED_ROUTE_KEY);
  } catch {
    return null;
  }
})();
selectRoute(
  routesIndex.routes.some((r) => r.id === savedRouteId) ? savedRouteId : routesIndex.defaultId
);

