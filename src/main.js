// ---------- Offline tile download ----------
// Fixed corridor covering the whole route from overview (z12) down to
// street-level (z16) detail. Not user-configurable on purpose — one button,
// one sensible default, no decisions to get wrong before a trip.
const OFFLINE_ZOOMS = [12, 13, 14, 15, 16];
const OFFLINE_BUFFER_TILES = 1;
const OFFLINE_SAMPLE_SPACING_METERS = 200;

const offlineStatus = document.getElementById('offline-status');
const progressWrap = document.getElementById('offline-progress');
const progressFill = document.getElementById('progress-fill');
const progressText = document.getElementById('progress-text');
const btnDownload = document.getElementById('btn-download');
const btnCancel = document.getElementById('btn-cancel');
const btnClearCache = document.getElementById('btn-clear-cache');

const BYTES_PER_TILE_ESTIMATE = 22 * 1024; // rough average for a 256px satellite JPEG tile

// Tiles are cached into one shared bucket, but "when did I last download"
// is tracked per route. (Older versions stored one un-keyed record for a
// since-removed route; that shape is just ignored.)
function readDownloadMeta() {
  try {
    const raw = JSON.parse(localStorage.getItem('offlineDownloadMeta') || 'null');
    return raw && !raw.timestamp ? raw : {};
  } catch {
    return {};
  }
}
function writeDownloadMeta(id, meta) {
  const all = readDownloadMeta();
  all[id] = meta;
  localStorage.setItem('offlineDownloadMeta', JSON.stringify(all));
}

async function refreshCacheStatus() {
  const count = await getCachedTileCount();
  const meta = readDownloadMeta()[routeId];
  const lines = [];
  if (count === 0) {
    lines.push('No offline tiles cached yet.');
  } else {
    lines.push(
      `${count.toLocaleString()} tiles cached for all routes (~${(
        (count * BYTES_PER_TILE_ESTIMATE) /
        1024 /
        1024
      ).toFixed(0)} MB).`
    );
  }
  if (meta?.timestamp) {
    const failed = meta.failed ? ` (${meta.failed} tiles failed — try downloading again)` : '';
    lines.push(`This route last downloaded: ${new Date(meta.timestamp).toLocaleString()}.${failed}`);
  } else {
    lines.push('This route has not been downloaded yet.');
  }
  offlineStatus.textContent = lines.join(' ');
}

function refreshOfflineEstimate() {
  const mb = Math.round((currentTileList().length * BYTES_PER_TILE_ESTIMATE) / 1024 / 1024);
  document.getElementById('offline-route-name').textContent = route.name;
  document.getElementById('offline-estimate').textContent = `about ${mb} MB`;
}

function currentTileList() {
  return computeCorridorTiles(
    route.track,
    route.distances,
    OFFLINE_ZOOMS,
    OFFLINE_BUFFER_TILES,
    OFFLINE_SAMPLE_SPACING_METERS
  );
}

let activeDownload = null;

btnDownload.addEventListener('click', () => {
  const tiles = currentTileList();
  const downloadRouteId = routeId; // the user may switch routes mid-download

  btnDownload.hidden = true;
  btnCancel.hidden = false;
  progressWrap.hidden = false;
  progressFill.style.width = '0%';
  progressText.textContent = `0 / ${tiles.length}`;

  activeDownload = downloadTiles(tiles, {
    concurrency: 6,
    onProgress: ({ done, failed, total }) => {
      const pct = total ? Math.round((done / total) * 100) : 100;
      progressFill.style.width = pct + '%';
      progressText.textContent = `${done} / ${total}${failed ? ` (${failed} failed)` : ''}`;
    },
  });

  activeDownload.promise.then(({ cancelled, failed }) => {
    btnDownload.hidden = false;
    btnCancel.hidden = true;
    progressWrap.hidden = true;
    activeDownload = null;
    if (!cancelled) {
      writeDownloadMeta(downloadRouteId, {
        timestamp: Date.now(),
        zooms: OFFLINE_ZOOMS,
        tileCount: tiles.length,
        failed,
      });
    }
    refreshCacheStatus();
  });
});

btnCancel.addEventListener('click', () => {
  if (activeDownload) activeDownload.cancel();
});

btnClearCache.addEventListener('click', async () => {
  await clearTileCache();
  localStorage.removeItem('offlineDownloadMeta');
  refreshCacheStatus();
});

